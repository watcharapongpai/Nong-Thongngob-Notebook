@pytest.mark.parametrize("messages,expected,has_cards", DEMO, ids=[" > ".join(d[0]) for d in DEMO])
def test_demo_question(messages, expected, has_cards):
    sid = uuid.uuid4().hex
    BOT.welcome(sid)
    for m in messages:
        r = BOT.reply(sid, m)
    assert expected in r["text"], r["text"]
    assert bool(r["cards"]) == has_cards, r["text"]
    for c in r["cards"]:
        p = BOT.catalog.get(c["id"])
        assert (c["price"], c["promo"]) == (p.price, p.promo)
